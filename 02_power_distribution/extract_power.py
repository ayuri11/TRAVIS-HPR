"""
Convert the OpenMC 'power_distribution' mesh tally to W/m3 and write the OpenFOAM heat-source inputs.

    python extract_power.py [path/to/statepoint.100.h5]      (default: ../01_neutronics/statepoint.100.h5)

Writes into data/: power_density_3d.npy, axial_power_profile.csv, phase1_summary.json, fvModels_heatSource.txt
KNOWN ISSUE: the voxel volume below assumes a 45 cm half-width but the run used 60 cm, and the 1/12 wedge
sum is normalised as a full core. See docs/KNOWN_ISSUES.md (#1) before using the absolute W/m3 values.
"""
import os
import sys
import json
import numpy as np
import openmc

HERE = os.path.dirname(os.path.abspath(__file__))
DATA = os.path.join(HERE, 'data')
sp_path = sys.argv[1] if len(sys.argv) > 1 else os.path.join(HERE, '..', '01_neutronics', 'statepoint.100.h5')

print(f"Loading {sp_path}...")
sp = openmc.StatePoint(sp_path)
tally = sp.get_tally(name='power_distribution')
print(f"Tally loaded: {tally.name}")
print(f"Tally scores: {tally.scores}")

# heating score: eV per source neutron, flattened mesh
heating_mean = tally.get_values(scores=['heating'], value='mean').flatten()
heating_std = tally.get_values(scores=['heating'], value='std_dev').flatten()
flux_mean = tally.get_values(scores=['flux'], value='mean').flatten()

print(f"\nRaw heating array shape: {heating_mean.shape}")
print(f"Mesh dimensions: 50 x 50 x 28 = {50*50*28} cells")
print(f"Total heating (sum): {heating_mean.sum():.4e} eV/source-neutron")

P_total_W = 2.5e6
eV_to_J = 1.60218e-19

# mesh geometry; must match Define_OpenMC.py
core_radius = 45.0   # cm (see KNOWN ISSUE above)
core_height = 160.0  # cm
mesh_nx, mesh_ny, mesh_nz = 50, 50, 28

mesh_x_span = 2 * core_radius
mesh_y_span = 2 * core_radius
mesh_z_span = core_height

cell_vol_cm3 = (mesh_x_span/mesh_nx) * (mesh_y_span/mesh_ny) * (mesh_z_span/mesh_nz)
cell_vol_m3 = cell_vol_cm3 * 1e-6

print(f"\nMesh cell volume: {cell_vol_cm3:.4f} cm3 = {cell_vol_m3:.6e} m3")

# scale per-source-neutron heating so the mesh total equals P_total_W
total_heating_J = heating_mean.sum() * eV_to_J
norm_factor = P_total_W / total_heating_J

print(f"Total heating per source neutron: {total_heating_J:.4e} J/source-n")
print(f"Normalization factor: {norm_factor:.4e} source-n/s")

q_Wm3 = heating_mean * norm_factor * eV_to_J / cell_vol_m3

print(f"\nPower density (W/m3):")
print(f"  Maximum: {q_Wm3.max():.4e} W/m3")
print(f"  Minimum (nonzero): {q_Wm3[q_Wm3>0].min():.4e} W/m3")
print(f"  Mean (nonzero): {q_Wm3[q_Wm3>0].mean():.4e} W/m3")

total_power_check = (q_Wm3 * cell_vol_m3).sum()
print(f"Verification: integrated total power = {total_power_check/1e6:.4f} MWth")

# OpenMC mesh ordering: z slowest, x fastest -> reorder to (x, y, z)
q_3d = q_Wm3.reshape((mesh_nz, mesh_ny, mesh_nx))
q_3d_xyz = q_3d.transpose((2, 1, 0))

print(f"\n3D power density array shape (x,y,z): {q_3d_xyz.shape}")

# axial profile: mean over x,y
axial_profile = q_3d_xyz.mean(axis=(0, 1))
axial_z = np.linspace(-core_height/2, core_height/2, mesh_nz)

print(f"\nAxial power profile (W/m3):")
for i, (z, q) in enumerate(zip(axial_z, axial_profile)):
    bar = '█' * int(q / axial_profile.max() * 30)
    print(f"  z={z:+7.1f} cm: {q:.3e} W/m3  {bar}")

os.makedirs(DATA, exist_ok=True)
np.save(os.path.join(DATA, 'power_density_3d.npy'), q_3d_xyz)
print(f"\nSaved: data/power_density_3d.npy  shape={q_3d_xyz.shape}")

np.savetxt(os.path.join(DATA, 'axial_power_profile.csv'),
           np.column_stack([axial_z, axial_profile]),
           delimiter=',',
           header='z_cm,q_Wm3',
           comments='')
print("Saved: data/axial_power_profile.csv")

summary = {
    'k_effective': float(sp.keff.n),
    'k_uncertainty': float(sp.keff.s),
    'P_total_MWth_reference': P_total_W / 1e6,
    'norm_factor': float(norm_factor),
    'q_max_Wm3': float(q_Wm3.max()),
    'q_mean_Wm3': float(q_Wm3[q_Wm3>0].mean()),
    'cell_vol_cm3': cell_vol_cm3,
    'mesh_dims': [mesh_nx, mesh_ny, mesh_nz],
    'total_power_check_MWth': float(total_power_check/1e6)
}

with open(os.path.join(DATA, 'phase1_summary.json'), 'w') as f:
    json.dump(summary, f, indent=2)
print("Saved: data/phase1_summary.json")

# one radially averaged heat-source entry per axial slice
print("\nGenerating OpenFOAM fvModels heat source entries...")

fv_lines = []
fv_lines.append("// OpenFOAM fvModels — heat source from OpenMC Phase 1")
fv_lines.append("// Generated by extract_power.py")
fv_lines.append("// Units: W/m³ normalized to 2.5 MWth reference power")
fv_lines.append("")

for k in range(mesh_nz):
    q_slice = q_3d_xyz[:,:,k].mean()
    z_lo = -core_height/2 + k * (core_height/mesh_nz)
    z_hi = z_lo + (core_height/mesh_nz)
    fv_lines.append(f"heatSource_axial_{k:02d}")
    fv_lines.append("{")
    fv_lines.append(f"    type            heatSource;")
    fv_lines.append(f"    selectionMode   cellZone;")
    fv_lines.append(f"    cellZone        fuelPin_axial_{k:02d};  // z: {z_lo:.1f} to {z_hi:.1f} cm")
    fv_lines.append(f"    q               {q_slice:.4e};  // W/m³")
    fv_lines.append("}")
    fv_lines.append("")

with open(os.path.join(DATA, 'fvModels_heatSource.txt'), 'w') as f:
    f.write('\n'.join(fv_lines))
print("Saved: data/fvModels_heatSource.txt")
